"""Publish complete readable prompts from the canonical battery; no model calls."""
import collections
import csv
import hashlib
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
BATTERY = ROOT / 'battery'
sys.path.insert(0, str(BATTERY))
import processor


def main():
    battery = processor.load_battery(BATTERY/'questions.csv', BATTERY/'battery_metadata.json')
    plan = processor.prepare(battery, 'reading-copy', {'provider':'reading-copy', 'model':'not-a-model-run'}, repeats=1)
    trials = {t['item_id']:t for t in plan['trials']}
    groups = collections.defaultdict(list)
    for item in battery['items']:
        groups[item['module']].append(item)
    dest = BATTERY/'question_book'
    dest.mkdir(exist_ok=True)
    intro = '''# Read the actual questions

The complete prompt content is included here, not in external papers or links.
Each module page below contains its scenarios/questions, displayed answer choices
where applicable, and required response fields. The CSV remains the canonical source.

**Scope:** this is a pilot set of original psychological-task-inspired probes.
It is not a complete or validated psychological assessment of an LLM. Many tasks
are deliberately simple, and 436 items includes condition variants of the same
scenarios—not 436 independent psychological questions. References motivate task
design; they are not locations of missing questions or validation of these items.
Some tasks may have ceiling effects, and ambiguous items/scoring require review
before substantive conclusions. Open-ended creativity and distinctions require
human review. Deception-related choices do not establish a clinical Dark Triad trait.

## Shared system prompt

This instruction accompanies every individual task:

```text
'''+battery['system_prompt']+'''
```

## Complete prompts by module

Module headings, scoring descriptions, and limits are for researchers. Send only
the system prompt above and the individual prompt block to a tested model.
The displayed option order is one deterministic presentation; `prepare` rotates
orders across repetitions and records the mapping. For actual scored runs, use
the prompts and trial IDs generated by `processor.py prepare`.

'''
    overview = [intro]
    csv_rows = []
    for module, items in groups.items():
        meta = battery['modules'][module]
        overview.append(f'- [{meta["title"]} ({module})](question_book/{module}.md) — {len(items)} instantiated items\n')
        parts = [f'# {meta["title"]} ({module})\n\n', '[Back to all questions](../QUESTIONS.md)\n\n',
                 f'Researcher scoring note: {meta["scoring"]}\n\n',f'Interpretation limit: {meta["limit"]}\n\n',
                 'The following blocks contain the complete user prompts. Each uses the shared system prompt in the index.\n\n']
        for item in items:
            trial = trials[item['id']]
            prompt = trial['messages'][1]['content']
            assert item['stem'] in prompt
            assert all(value in prompt for value in item['options'].values())
            parts.append(f'## {item["id"]}\n\n```text\n{prompt}\n```\n\n')
            csv_rows.append({'item_id':item['id'], 'module':module, 'system_prompt':trial['messages'][0]['content'], 'complete_user_prompt':prompt})
        (dest/f'{module}.md').write_text(''.join(parts), encoding='utf-8')
    (BATTERY/'QUESTIONS.md').write_text(''.join(overview),encoding='utf-8')
    with (BATTERY/'complete_prompts.csv').open('w',encoding='utf-8',newline='') as handle:
        writer=csv.DictWriter(handle,fieldnames=['item_id','module','system_prompt','complete_user_prompt'])
        writer.writeheader();writer.writerows(csv_rows)
    assert len(csv_rows)==len(battery['items']) and len(trials)==len(csv_rows)
    manifest={p.relative_to(BATTERY).as_posix():hashlib.sha256(p.read_bytes()).hexdigest()
              for p in BATTERY.rglob('*') if p.is_file() and '__pycache__' not in p.parts and p.name!='SHA256.json'}
    processor.write_json(BATTERY/'SHA256.json',manifest)
    print(f'Exported and checked {len(csv_rows)} complete prompts across {len(groups)} module pages.')


if __name__ == '__main__':
    main()
